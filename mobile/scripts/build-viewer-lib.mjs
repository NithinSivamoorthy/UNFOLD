// Inlines @google/model-viewer (UMD build, includes three.js) into a TS module so the
// 3D viewer WebView works fully offline — no CDN fetch at runtime.
// Runs automatically on `npm install` (postinstall). Output is gitignored.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = dirname(require.resolve('@google/model-viewer/package.json'));
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;
const src = readFileSync(join(pkgDir, 'dist', 'model-viewer-umd.min.js'), 'utf8')
  // Never let the library text terminate the inline <script> tag.
  .replace(/<\/script/gi, '<\\/script');

const outDir = join(root, 'src', 'viewer');
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, 'model-viewer-lib.generated.ts'),
  `// AUTO-GENERATED by scripts/build-viewer-lib.mjs from @google/model-viewer@${version}. Do not edit.\n` +
    `export const MODEL_VIEWER_VERSION = ${JSON.stringify(version)};\n` +
    `export const MODEL_VIEWER_LIB = ${JSON.stringify(src)};\n`
);
console.log(`[unfold] inlined model-viewer@${version} (${(src.length / 1024).toFixed(0)} KB)`);
